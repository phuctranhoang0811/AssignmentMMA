async function webhook(order: PaymentOrder, overrides = {}) {
  const data = { orderCode: order.orderCode, amount: order.total, description: 'VQRIO123', accountNumber: '12345678',
    reference: 'TF230204212323', transactionDateTime: '2023-02-04 18:25:00', currency: 'VND',
    paymentLinkId: 'test-link', code: '00', desc: 'Thành công', counterAccountBankId: '',
    counterAccountBankName: '', counterAccountName: '', counterAccountNumber: '', virtualAccountName: '', virtualAccountNumber: '', ...overrides };
  return { code: '00', desc: 'success', success: true, data,
    signature: await payos.crypto.createSignatureFromObj(data, payos.checksumKey) };
}
class MemoryStore {
  orders = new Map<string, PaymentOrder>();
  async get(id: string) { return this.orders.get(id) ?? null; }
  async reserve(uid: string, key: string, input: Checkout) {
    const { id, fingerprint } = orderIdentity(uid, key, input);
    const old = this.orders.get(id);
    if (old) {
      if (old.fingerprint !== fingerprint) throw new HttpError(409, 'Conflict');
      return old;
    }
    const pricing = priceCheckout(input, [product]);
    const order: PaymentOrder = { id, fingerprint, userId: uid, orderCode: 123, checkout: input, ...pricing,
      total: pricing.pricing.total, paymentStatus: 'PENDING', createdAt: new Date().toISOString() };
    this.orders.set(id, order); return order;
  }
  async attach(id: string, payment: PaymentLink) {
    const order = { ...this.orders.get(id)!, payment }; this.orders.set(id, order); return order;
  }
  async pay(data: PaidData) {
    const order = [...this.orders.values()].find(o => o.orderCode === data.orderCode);
    if (!order) return null;
    const paid = settle(order, data); this.orders.set(paid.id, paid); return paid;
  }
}
