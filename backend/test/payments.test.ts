test('Socket.IO refuses invalid tokens and delivers only to the owner', async t => {
  const f = await fixture(t);
  const bad = connect(f.url, { auth: { token: 'invalid' }, reconnection: false });
  t.after(() => { bad.disconnect(); });
  await new Promise<void>((resolve, reject) => {
    bad.on('connect', () => reject(new Error('Unexpected authentication')));
    bad.on('connect_error', () => resolve());
    setTimeout(() => reject(new Error('Socket auth timeout')), 2000).unref();
  });
  const owner = connect(f.url, { auth: { token: 'user-a' }, reconnection: false });
  const other = connect(f.url, { auth: { token: 'user-b' }, reconnection: false });
  t.after(() => { owner.disconnect(); other.disconnect(); });
  await Promise.all([owner, other].map(socket => new Promise<void>((resolve, reject) => {
    socket.on('connect', resolve); socket.on('connect_error', reject);
  })));
  let leaked = false; other.on('payment:updated', () => { leaked = true; });
  const eventReceived = new Promise<{ paymentStatus: string }>((resolve, reject) => {
    owner.once('payment:updated', resolve);
    setTimeout(() => reject(new Error('Payment event timeout')), 2000).unref();
  });
  const order = await (await f.create()).json();
  await f.request('/api/webhooks/payos', await webhook(f.store.orders.get(order.id)!));
  assert.equal((await eventReceived).paymentStatus, 'PAID');
  // A request/response round trip gives queued socket packets a chance to arrive.
  await f.request(`/api/orders/${order.id}`);
  assert.equal(leaked, false);
});

function transactionStore(order: PaymentOrder) {
  const docs = new Map<string, unknown>([
    [`payment_orders/${order.id}`, order],
    [`payment_codes/${order.orderCode}`, { orderId: order.id }],
  ]);
  type Ref = { path: string };
  const db = {
    collection: (name: string) => ({ doc: (id: string) => ({ path: `${name}/${id}` }) }),
    runTransaction: async (callback: (tx: unknown) => Promise<unknown>) => {
      const staged = new Map(docs);
      const result = await callback({
        get: async (ref: Ref) => ({ exists: staged.has(ref.path), data: () => staged.get(ref.path) }),
        update: (ref: Ref, update: object) => { staged.set(ref.path, { ...(staged.get(ref.path) as object), ...update }); },
        create: (ref: Ref, value: unknown) => {
          if (staged.has(ref.path)) throw new Error('Document already exists');
          staged.set(ref.path, value);
        },
      });
      docs.clear(); for (const [key, value] of staged) docs.set(key, value);
      return result;
    },
  } as unknown as ConstructorParameters<typeof OrderStore>[0];
  return { store: new OrderStore(db), docs };
}
test('production store publishes a paid customer order atomically and only once', async () => {
  const pending = await new MemoryStore().reserve('user-a', 'publish-test-key-123', { ...checkout, needCutlery: true });
  const { store, docs } = transactionStore(pending);
  const event = (await webhook(pending)).data;
  await store.pay(event);
  const first = docs.get(`orders/${pending.id}`) as Record<string, unknown>;
  assert.equal(first.paymentStatus, 'PAID');
  assert.equal(first.needCutlery, true);
  assert.equal(first.userId, 'user-a');
  assert.deepEqual(first.customer, checkout.customer);
  assert.equal(first.total, pending.total);
  assert.equal(first.orderCode, String(pending.orderCode));
  assert.equal(first.status, 'PENDING_CONFIRMATION');
  await store.pay(event);
  assert.equal(docs.get(`orders/${pending.id}`), first);
});

